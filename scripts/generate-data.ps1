# === BRAILLE (U+2800-U+28FF) ===
Write-Host "Generating 256 braille patterns..."
for ($cp = 0x2800; $cp -le 0x28FF; $cp++) {
    $c = [char]::ConvertFromUtf32($cp)
    $dots = $cp - 0x2800
    $d = @()
    if ($dots -band 0x01) { $d += 1 }; if ($dots -band 0x02) { $d += 2 }
    if ($dots -band 0x04) { $d += 3 }; if ($dots -band 0x08) { $d += 4 }
    if ($dots -band 0x10) { $d += 5 }; if ($dots -band 0x20) { $d += 6 }
    if ($dots -band 0x40) { $d += 7 }; if ($dots -band 0x80) { $d += 8 }
    $ds = if ($d.Count -gt 0) { " DOTS-" + ($d -join "") } else { "" }
    Add-Entry $c "U+$($cp.ToString('X4'))" "BRAILLE PATTERN$ds" "Braille Patterns" "So"
}

